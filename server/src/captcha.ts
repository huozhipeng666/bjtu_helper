function pick<T>(arr: T[]): T {
  return arr[randomInt(arr.length)]
}

function rnd(min: number, max: number): number {
  return randomInt(min, max + 1)
}

export function makeCaptchaCode(len = 4): string {
  let s = ''
  for (let i = 0; i < len; i++) s += CHARS[randomInt(CHARS.length)]
  return s
}

/**
 * 把一个字符展开成点阵 `<path>` 的 d 属性。
 *
 * 每个亮格是一个小方块子路径（`M x y h w v h h -w z`），全部塞进同一个 path 里，
 * 靠 fill 一次画完 —— 比每个点一个 `<rect>` 体积小一半，且不暴露字符。
 *
 * 每格四周留 0.3px 的缝（`CELL_INSET`）：点阵字如果格子紧贴，相邻笔画会糊成一片，
 * 留缝之后"哪一格亮着"一眼可辨 —— 这是这类点阵验证码可读性的关键，
 * 而它同时也不影响机器识别难度（读的仍是图像，不是文本）。
 */
const CELL_INSET = 0.3

function glyphPath(ch: string, x0: number, y0: number, cw: number, chh: number): string {
  const rows = GLYPHS[ch]
  if (!rows) return ''
  const w = (cw - CELL_INSET * 2).toFixed(1)
  const h = (chh - CELL_INSET * 2).toFixed(1)
  const parts: string[] = []
  for (let r = 0; r < rows.length; r++) {
    const row = rows[r]
    for (let c = 0; c < row.length; c++) {
      if (row[c] !== '#') continue
      const x = (x0 + c * cw + CELL_INSET).toFixed(1)
      const y = (y0 + r * chh + CELL_INSET).toFixed(1)
      parts.push(`M${x} ${y}h${w}v${h}h-${w}z`)
    }
  }
  return parts.join('')
}

/**
 * 把验证码渲染成 SVG 字符串。
 *
 * 字符集固定（不含 < > & " '），且输出里**只有数字坐标**，因此不存在注入风险，
 * 前端可安全地用 innerHTML 渲染（见 AuthForm.tsx 的注释）。
 */
export function renderCaptchaSvg(code: string): string {
  const W = 128
  const H = 50
  const out: string[] = []
  out.push(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" role="img" aria-label="图形验证码">`
  )
  out.push(`<rect width="${W}" height="${H}" rx="9" fill="#f2f5f9"/>`)

  // 干扰线（在字符之下，不遮挡可读性）
  for (let i = 0; i < 3; i++) {
    out.push(
      `<path d="M${rnd(0, W)} ${rnd(4, H - 4)} C ${rnd(0, W)} ${rnd(0, H)}, ${rnd(0, W)} ${rnd(0, H)}, ${rnd(0, W)} ${rnd(4, H - 4)}" ` +
        `stroke="${pick(NOISE_STROKE)}" stroke-width="1.5" fill="none"/>`
    )
  }
  // 噪点
  for (let i = 0; i < 26; i++) {
    out.push(`<circle cx="${rnd(0, W)}" cy="${rnd(0, H)}" r="1" fill="${pick(NOISE_STROKE)}" opacity="0.75"/>`)
  }

  const n = code.length
  const slot = W / n
  for (let i = 0; i < n; i++) {
    const ch = code[i]
    /* 每格尺寸 3.9~4.4：字形整体约 20×28，与原来 font-size 27 的观感接近；
       随机化是为了让"同一个字母在两次请求里像素完全一样"这件事不成立（模板匹配失效）。 */
    const cw = 3.9 + randomInt(0, 6) / 10
    const chh = cw
    const glyphW = cw * 5
    const glyphH = chh * 7
    const x0 = slot * i + (slot - glyphW) / 2 + rnd(-2, 2)
    const y0 = (H - glyphH) / 2 + rnd(-2, 2)
    const cx = x0 + glyphW / 2
    const cy = y0 + glyphH / 2
    const rot = rnd(-18, 18)
    const d = glyphPath(ch, x0, y0, cw, chh)
    if (!d) continue
    out.push(
      `<path d="${d}" fill="${pick(INK)}" transform="rotate(${rot} ${cx.toFixed(1)} ${cy.toFixed(1)})"/>`
    )
  }
  out.push('</svg>')
  return out.join('')
}
